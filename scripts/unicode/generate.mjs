// Generates packages/text/src/unicode/data.generated.ts from the Unicode
// Character Database (UCD) 15.1.0, the version of the ICU in Chromium 141.
//
//   node scripts/unicode/generate.mjs <ucd-dir>
//
// <ucd-dir> holds these UCD files, read as plain data:
//   LineBreak.txt, EastAsianWidth.txt, Scripts.txt, DerivedCoreProperties.txt,
//   GraphemeBreakProperty.txt, emoji-data.txt, DerivedGeneralCategory.txt,
//   PropertyValueAliases.txt
// from https://www.unicode.org/Public/15.1.0/ucd/ (Unicode License v3).
//
// Each property becomes a run-length table: sorted range starts with a
// value index, packed as start << 8 | value into a Uint32Array and stored
// as base64.
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const dir = process.argv[2];
if (!dir) throw new Error("usage: node scripts/unicode/generate.mjs <ucd-dir>");
const outPath = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "packages", "text", "src", "unicode", "data.generated.ts");

/** Parses `start..end ; value` lines into an array of [start, end, value]. */
function parse(file, field = 1, filter = null) {
  const out = [];
  for (const raw of readFileSync(join(dir, file), "utf8").split("\n")) {
    const line = raw.replace(/#.*/, "").trim();
    if (!line) continue;
    const parts = line.split(";").map((s) => s.trim());
    if (filter && !filter(parts)) continue;
    const [a, b] = parts[0].split("..");
    out.push([parseInt(a, 16), parseInt(b ?? a, 16), parts[field]]);
  }
  return out;
}

/** Builds a dense value array for 0..10FFFF then run-length encodes it. */
function table(ranges, values, fallback) {
  const index = new Map(values.map((v, i) => [v, i]));
  const dense = new Uint8Array(0x110000).fill(index.get(fallback));
  for (const [a, b, v] of ranges) {
    const i = index.get(v);
    if (i === undefined) throw new Error(`unknown value ${v}`);
    dense.fill(i, a, b + 1);
  }
  const runs = [];
  for (let cp = 0; cp < 0x110000; cp++) if (cp === 0 || dense[cp] !== dense[cp - 1]) runs.push(((cp << 8) | dense[cp]) >>> 0);
  const bytes = Buffer.from(new Uint32Array(runs).buffer);
  return { runs: runs.length, base64: bytes.toString("base64") };
}

const LB = ["XX", "AI", "AK", "AL", "AP", "AS", "B2", "BA", "BB", "BK", "CB", "CJ", "CL", "CM", "CP", "CR", "EB", "EM", "EX", "GL", "H2", "H3", "HL", "HY", "ID", "IN", "IS", "JL", "JT", "JV", "LF", "NL", "NS", "NU", "OP", "PO", "PR", "QU", "RI", "SA", "SG", "SP", "SY", "VF", "VI", "WJ", "ZW", "ZWJ"];
const GCB = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend", "SpacingMark", "L", "V", "T", "LV", "LVT"];
const INCB = ["None", "Linker", "Consonant", "Extend"];
const GC = ["Cn", "Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No", "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po", "Sm", "Sc", "Sk", "So", "Zs", "Zl", "Zp", "Cc", "Cf", "Cs", "Co"];

// Scripts: long names to ISO 15924 codes.
const scriptCodes = new Map();
for (const raw of readFileSync(join(dir, "PropertyValueAliases.txt"), "utf8").split("\n")) {
  const m = /^sc\s*;\s*(\w+)\s*;\s*(\w+)/.exec(raw);
  if (m) scriptCodes.set(m[2], m[1]);
}
const scriptRanges = parse("Scripts.txt").map(([a, b, v]) => [a, b, scriptCodes.get(v) ?? v]);
const SC = ["Zzzz", "Zyyy", "Zinh", ...[...new Set(scriptRanges.map((r) => r[2]))].filter((s) => s !== "Zyyy" && s !== "Zinh").sort()];

// East Asian Width F, W or H (LB30, LB19a/b): 1, else 0. Extended_Pictographic: 2. Emoji_Presentation: 4.
const flags = new Uint8Array(0x110000);
for (const [a, b, v] of parse("EastAsianWidth.txt")) if (v === "F" || v === "W" || v === "H") for (let c = a; c <= b; c++) flags[c] |= 1;
for (const [a, b, v] of parse("emoji-data.txt")) {
  const bit = v === "Extended_Pictographic" ? 2 : v === "Emoji_Presentation" ? 4 : v === "Emoji" ? 8 : 0;
  if (bit) for (let c = a; c <= b; c++) flags[c] |= bit;
}
const flagRanges = [];
for (let c = 0; c < 0x110000; c++) if (flags[c]) flagRanges.push([c, c, String(flags[c])]);

const tables = {
  lineBreak: table(parse("LineBreak.txt"), LB, "XX"),
  graphemeBreak: table(parse("GraphemeBreakProperty.txt"), GCB, "Other"),
  indicConjunctBreak: table(parse("DerivedCoreProperties.txt", 2, (p) => p[1] === "InCB"), INCB, "None"),
  generalCategory: table(parse("DerivedGeneralCategory.txt"), GC, "Cn"),
  script: table(scriptRanges, SC, "Zzzz"),
  flags: table(flagRanges, Array.from({ length: 16 }, (_, i) => String(i)), "0"),
};

const lines = [
  "// Generated by scripts/unicode/generate.mjs from the Unicode Character Database 15.1.0.",
  "// Unicode data is Copyright (c) 1991-2026 Unicode, Inc., licensed under the Unicode License v3",
  "// (see THIRD_PARTY_NOTICES.md). Do not edit by hand.",
  "",
  `export const UNICODE_VERSION = "15.1.0";`,
  `export const LINE_BREAK_VALUES = ${JSON.stringify(LB)} as const;`,
  `export const GRAPHEME_BREAK_VALUES = ${JSON.stringify(GCB)} as const;`,
  `export const INDIC_CONJUNCT_BREAK_VALUES = ${JSON.stringify(INCB)} as const;`,
  `export const GENERAL_CATEGORY_VALUES = ${JSON.stringify(GC)} as const;`,
  `export const SCRIPT_VALUES = ${JSON.stringify(SC)} as const;`,
  "/** Run tables: base64 of a Uint32Array of `start << 8 | valueIndex`, sorted by start. */",
  "export const TABLES = {",
  ...Object.entries(tables).map(([k, t]) => `  /** ${t.runs} runs */\n  ${k}: "${t.base64}",`),
  "};",
  "",
];
writeFileSync(outPath, lines.join("\n"));
for (const [k, t] of Object.entries(tables)) console.log(k, t.runs, "runs", t.base64.length, "chars");
